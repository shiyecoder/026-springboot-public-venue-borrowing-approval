-- 校内公共场地借用与审批管理系统 · 初始化脚本
-- 库名 new_026，字符集 utf8mb4，测试数据时间分布在近 6 个月
DROP DATABASE IF EXISTS new_026;
CREATE DATABASE new_026 DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE new_026;

-- ============ 场地档案 ============
CREATE TABLE venue (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  code VARCHAR(50) NOT NULL COMMENT '场地编号',
  name VARCHAR(100) NOT NULL COMMENT '场地名称',
  campus VARCHAR(50) NOT NULL COMMENT '所在校区',
  building VARCHAR(100) COMMENT '楼宇/区域',
  capacity INT NOT NULL DEFAULT 0 COMMENT '容量(人)',
  area DECIMAL(10,2) COMMENT '面积(㎡)',
  allow_activity VARCHAR(200) NOT NULL COMMENT '适用活动',
  equipment VARCHAR(300) NOT NULL COMMENT '设备清单',
  open_time VARCHAR(100) COMMENT '开放时段',
  dept_name VARCHAR(100) COMMENT '管理部门',
  fee_standard DECIMAL(10,2) DEFAULT 0 COMMENT '费用标准(元/场)',
  status VARCHAR(20) DEFAULT '可用' COMMENT '场地状态',
  image VARCHAR(200) COMMENT '现场图片',
  remark VARCHAR(500),
  deleted TINYINT DEFAULT 0,
  version INT DEFAULT 0,
  create_time DATETIME,
  update_time DATETIME,
  UNIQUE KEY uk_venue_code (code),
  KEY idx_venue_campus (campus),
  KEY idx_venue_status (status)
) COMMENT '校内公共场地主档';

-- ============ 场地物资 ============
CREATE TABLE venue_item (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  venue_id BIGINT NOT NULL COMMENT '所属场地',
  item_name VARCHAR(100) NOT NULL COMMENT '物资名称',
  item_type VARCHAR(50) COMMENT '物资类别',
  total_qty INT NOT NULL DEFAULT 0 COMMENT '库存总数',
  unit VARCHAR(20) DEFAULT '个',
  status VARCHAR(20) DEFAULT '正常',
  remark VARCHAR(300),
  deleted TINYINT DEFAULT 0,
  create_time DATETIME,
  update_time DATETIME,
  KEY idx_item_venue (venue_id)
) COMMENT '场地物资库';

-- ============ 借用申请 ============
CREATE TABLE venue_application (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  apply_no VARCHAR(50) NOT NULL COMMENT '申请编号',
  title VARCHAR(200) NOT NULL COMMENT '活动主题',
  activity_type VARCHAR(50) NOT NULL COMMENT '活动类型',
  venue_id BIGINT NOT NULL COMMENT '场地ID',
  venue_name VARCHAR(100) COMMENT '场地名称',
  applicant_id BIGINT NOT NULL COMMENT '申请人ID',
  applicant_name VARCHAR(50) COMMENT '申请人',
  dept_name VARCHAR(100) COMMENT '申请单位',
  people_count INT NOT NULL DEFAULT 0 COMMENT '参与人数',
  setup_start DATETIME COMMENT '布场开始',
  start_time DATETIME COMMENT '活动开始',
  end_time DATETIME COMMENT '活动结束',
  teardown_end DATETIME COMMENT '撤场结束',
  process_desc VARCHAR(1000) COMMENT '活动流程',
  equip_need VARCHAR(500) COMMENT '设备物资需求',
  outsider_info VARCHAR(500) COMMENT '外来人员',
  attach_file VARCHAR(500) COMMENT '附件路径',
  risk_level VARCHAR(50) DEFAULT '普通' COMMENT '风险等级(普通/大型/夜间/户外/用电搭建)',
  need_security TINYINT DEFAULT 0 COMMENT '是否需安保审批',
  status VARCHAR(30) NOT NULL DEFAULT '草稿' COMMENT '业务状态',
  current_node VARCHAR(30) COMMENT '当前节点',
  handler_name VARCHAR(50) COMMENT '当前责任人',
  deadline DATETIME COMMENT '处理截止时间',
  reject_reason VARCHAR(500) COMMENT '驳回/退回原因',
  cancel_flag TINYINT DEFAULT 0,
  version INT DEFAULT 0,
  deleted TINYINT DEFAULT 0,
  create_time DATETIME,
  update_time DATETIME,
  UNIQUE KEY uk_apply_no (apply_no),
  KEY idx_apply_status (status),
  KEY idx_apply_venue (venue_id),
  KEY idx_apply_time (start_time, end_time)
) COMMENT '场地借用申请';

-- ============ 审批记录 ============
CREATE TABLE application_approval (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  apply_id BIGINT NOT NULL,
  node VARCHAR(50) NOT NULL COMMENT '审批节点',
  approver_id BIGINT,
  approver_name VARCHAR(50),
  result VARCHAR(20) COMMENT '通过/退回/驳回',
  opinion VARCHAR(500) COMMENT '审批意见',
  cost_hours DECIMAL(6,2) COMMENT '审批耗时(小时)',
  create_time DATETIME,
  KEY idx_appr_apply (apply_id)
) COMMENT '审批留痕';

-- ============ 物资预留 ============
CREATE TABLE item_reservation (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  apply_id BIGINT NOT NULL,
  item_id BIGINT NOT NULL,
  item_name VARCHAR(100),
  qty INT NOT NULL DEFAULT 0,
  status VARCHAR(20) DEFAULT '预留' COMMENT '预留/已交付/已归还',
  create_time DATETIME,
  KEY idx_res_apply (apply_id),
  KEY idx_res_item (item_id)
) COMMENT '物资预留明细';

-- ============ 入场交接 ============
CREATE TABLE handover_record (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  apply_id BIGINT NOT NULL,
  venue_state VARCHAR(300) COMMENT '场地现状',
  items_delivered VARCHAR(500) COMMENT '交付物资',
  electric_reading DECIMAL(10,2) COMMENT '电表示数',
  key_info VARCHAR(200) COMMENT '钥匙/门禁卡',
  photo VARCHAR(300) COMMENT '交接照片',
  applicant_confirm VARCHAR(50) COMMENT '申请人确认',
  manager_confirm VARCHAR(50) COMMENT '管理员确认',
  handover_time DATETIME,
  remark VARCHAR(500),
  create_time DATETIME,
  KEY idx_ho_apply (apply_id)
) COMMENT '入场交接记录';

-- ============ 巡场记录 ============
CREATE TABLE patrol_record (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  apply_id BIGINT NOT NULL,
  patrol_time DATETIME,
  patrol_user VARCHAR(50),
  issue_type VARCHAR(50) COMMENT '正常/超员/违规用电/噪音/通道堵塞',
  over_capacity TINYINT DEFAULT 0,
  illegal_power TINYINT DEFAULT 0,
  noise_level INT COMMENT '噪音值(dB)',
  aisle_blocked TINYINT DEFAULT 0,
  description VARCHAR(500),
  photo VARCHAR(300),
  handle_result VARCHAR(300),
  create_time DATETIME,
  KEY idx_patrol_apply (apply_id)
) COMMENT '活动巡场记录';

-- ============ 撤场验收 ============
CREATE TABLE venue_acceptance (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  apply_id BIGINT NOT NULL,
  cleaner_ok TINYINT DEFAULT 1 COMMENT '清洁合格',
  facility_ok TINYINT DEFAULT 1 COMMENT '设施完好',
  item_ok TINYINT DEFAULT 1 COMMENT '物资齐全',
  key_returned TINYINT DEFAULT 1 COMMENT '钥匙归还',
  damage_flag TINYINT DEFAULT 0 COMMENT '是否损坏',
  damage_desc VARCHAR(500),
  compensate_amount DECIMAL(10,2) DEFAULT 0 COMMENT '赔偿金额',
  review_status VARCHAR(20) DEFAULT '待复核' COMMENT '待复核/已确认',
  result VARCHAR(20) COMMENT '通过/驳回',
  photo VARCHAR(300),
  acceptor VARCHAR(50),
  accept_time DATETIME,
  remark VARCHAR(500),
  create_time DATETIME,
  KEY idx_acc_apply (apply_id)
) COMMENT '撤场验收记录';

-- ============ 线下费用 ============
CREATE TABLE fee_record (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  apply_id BIGINT NOT NULL,
  fee_type VARCHAR(50) COMMENT '场地费/押金/物资费/损坏赔偿',
  amount DECIMAL(10,2) NOT NULL DEFAULT 0,
  pay_status VARCHAR(20) DEFAULT '未收' COMMENT '未收/已收/已退/部分退',
  handler VARCHAR(50),
  pay_time DATETIME,
  remark VARCHAR(300),
  create_time DATETIME,
  KEY idx_fee_apply (apply_id)
) COMMENT '线下费用登记';

-- ============ 创新模块：准备清单规则 ============
CREATE TABLE prep_rule (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  rule_key VARCHAR(50) NOT NULL COMMENT '因素键',
  rule_name VARCHAR(50) NOT NULL,
  weight DECIMAL(5,2) NOT NULL COMMENT '权重(%)',
  version VARCHAR(20) DEFAULT 'v3',
  enabled TINYINT DEFAULT 1,
  effective_time DATETIME,
  remark VARCHAR(300),
  create_time DATETIME,
  UNIQUE KEY uk_rule_key (rule_key)
) COMMENT '准备清单权重规则';

CREATE TABLE prep_score (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  apply_id BIGINT NOT NULL,
  rule_version VARCHAR(20),
  input_snapshot VARCHAR(1000) COMMENT '输入快照(JSON)',
  detail_json VARCHAR(2000) COMMENT '明细分与清单(JSON)',
  total_score DECIMAL(6,2),
  level VARCHAR(20) COMMENT '准备充分/准备较充分/准备不足',
  unmet VARCHAR(500) COMMENT '未满足条件',
  advice VARCHAR(500) COMMENT '可改进项',
  manual_level VARCHAR(20) COMMENT '人工修正等级',
  manual_reason VARCHAR(500),
  manual_by VARCHAR(50),
  manual_time DATETIME,
  create_time DATETIME,
  KEY idx_score_apply (apply_id)
) COMMENT '准备清单计算留痕';

-- ============ 系统表 ============
CREATE TABLE sys_user (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  username VARCHAR(50) NOT NULL,
  password VARCHAR(100) NOT NULL,
  real_name VARCHAR(50),
  role VARCHAR(30),
  role_name VARCHAR(50),
  phone VARCHAR(30),
  avatar VARCHAR(200),
  dept_name VARCHAR(100),
  status TINYINT DEFAULT 1,
  last_login DATETIME,
  deleted TINYINT DEFAULT 0,
  create_time DATETIME,
  update_time DATETIME,
  UNIQUE KEY uk_user_name (username)
) COMMENT '用户';

CREATE TABLE sys_role (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  role_code VARCHAR(30) NOT NULL,
  role_name VARCHAR(50) NOT NULL,
  remark VARCHAR(300),
  status TINYINT DEFAULT 1,
  create_time DATETIME,
  UNIQUE KEY uk_role_code (role_code)
) COMMENT '角色';

CREATE TABLE sys_menu (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  parent_id BIGINT DEFAULT 0,
  name VARCHAR(50) NOT NULL,
  path VARCHAR(100),
  icon VARCHAR(50),
  sort_no INT DEFAULT 0,
  role_codes VARCHAR(200) COMMENT '可见角色,逗号分隔',
  hidden TINYINT DEFAULT 0
) COMMENT '菜单';

CREATE TABLE sys_dict (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  dict_type VARCHAR(50) NOT NULL,
  dict_label VARCHAR(50) NOT NULL,
  dict_value VARCHAR(50) NOT NULL,
  sort_no INT DEFAULT 0,
  status TINYINT DEFAULT 1
) COMMENT '字典';

CREATE TABLE sys_message (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  title VARCHAR(200),
  content VARCHAR(500),
  biz_no VARCHAR(50),
  biz_type VARCHAR(50),
  jump_url VARCHAR(200),
  receiver_id BIGINT,
  read_flag TINYINT DEFAULT 0,
  create_time DATETIME,
  KEY idx_msg_receiver (receiver_id)
) COMMENT '站内消息';

CREATE TABLE sys_log (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  user_id BIGINT,
  user_name VARCHAR(50),
  action VARCHAR(50),
  biz_no VARCHAR(50),
  detail VARCHAR(500),
  ip VARCHAR(50),
  create_time DATETIME,
  KEY idx_log_time (create_time)
) COMMENT '操作日志';

